




CREATE SEQUENCE SEQ_NEXO_CENARIO

    START WITH 1

    INCREMENT BY 1

    NOCYCLE;



CREATE SEQUENCE SEQ_NEXO_ALTERNATIVA

    START WITH 1

    INCREMENT BY 1

    NOCYCLE;



CREATE SEQUENCE SEQ_NEXO_DECISAO

    START WITH 1

    INCREMENT BY 1

    NOCYCLE;



CREATE SEQUENCE SEQ_NEXO_MITO_FATO

    START WITH 1

    INCREMENT BY 1

    NOCYCLE;






CREATE TABLE NEXO_CENARIO (

    ID_CENARIO           NUMBER(10)          NOT NULL,

    TITULO               VARCHAR2(150 CHAR)  NOT NULL,

    CATEGORIA            VARCHAR2(20 CHAR)   NOT NULL,

    SITUACAO             VARCHAR2(1000 CHAR) NOT NULL,

    OBJETIVO_EDUCACIONAL VARCHAR2(500 CHAR)  NOT NULL,

    FONTE_URL            VARCHAR2(1000 CHAR) NOT NULL,



    CONSTRAINT CENARIO_PK

        PRIMARY KEY (ID_CENARIO),



    CONSTRAINT CK_NEXO_CEN_CATEGORIA

        CHECK (CATEGORIA IN (

            'SAUDE',

            'AGRICULTURA',

            'INDUSTRIA',

            'PESQUISA',

            'ENERGIA'

        ))

);






CREATE TABLE NEXO_ALTERNATIVA (

    ID_ALTERNATIVA NUMBER(10)          NOT NULL,

    CENARIO_ID     NUMBER(10)          NOT NULL,

    ROTULO         VARCHAR2(1 CHAR)    NOT NULL,

    DESCRICAO      VARCHAR2(1000 CHAR) NOT NULL,

    FEEDBACK       VARCHAR2(1000 CHAR) NOT NULL,



    CONSTRAINT ALTERNATIVA_PK

        PRIMARY KEY (ID_ALTERNATIVA),



    CONSTRAINT ALTERNATIVA_CENARIO_FK

        FOREIGN KEY (CENARIO_ID)

        REFERENCES NEXO_CENARIO (ID_CENARIO),



    CONSTRAINT UK_NEXO_ALT_CEN_ROT

        UNIQUE (CENARIO_ID, ROTULO),



    CONSTRAINT CK_NEXO_ALT_ROTULO

        CHECK (ROTULO IN ('A', 'B'))

);






CREATE TABLE NEXO_MITO_FATO (

    ID_MITO_FATO   NUMBER(10)          NOT NULL,

    CENARIO_ID     NUMBER(10)          NOT NULL,

    AFIRMACAO      VARCHAR2(500 CHAR)  NOT NULL,

    CLASSIFICACAO  VARCHAR2(4 CHAR)    NOT NULL,

    EXPLICACAO     VARCHAR2(1000 CHAR) NOT NULL,

    FONTE_URL      VARCHAR2(1000 CHAR) NOT NULL,



    CONSTRAINT MITO_FATO_PK

        PRIMARY KEY (ID_MITO_FATO),



    CONSTRAINT MITO_FATO_CENARIO_FK

        FOREIGN KEY (CENARIO_ID)

        REFERENCES NEXO_CENARIO (ID_CENARIO),



    CONSTRAINT CK_NEXO_MF_CLASSIFICACAO

        CHECK (CLASSIFICACAO IN ('MITO', 'FATO'))

);






CREATE TABLE NEXO_DECISAO (

    ID_DECISAO     NUMBER(10)         NOT NULL,

    ALTERNATIVA_ID NUMBER(10)         NOT NULL,

    APELIDO        VARCHAR2(50 CHAR)  NOT NULL,

    DATA_ESCOLHA   TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,



    CONSTRAINT DECISAO_PK

        PRIMARY KEY (ID_DECISAO),



    CONSTRAINT DECISAO_ALTERNATIVA_FK

        FOREIGN KEY (ALTERNATIVA_ID)

        REFERENCES NEXO_ALTERNATIVA (ID_ALTERNATIVA)

);